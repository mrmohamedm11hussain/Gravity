function getGravityBooks() {

    let localBooks = [];

    try {
        localBooks =
            JSON.parse(
                localStorage.getItem("gravity_m11_books")
            ) || [];
    } catch {
        localBooks = [];
    }

    return [
        ...gravityBooks,
        ...localBooks
    ];
}


function searchGravityBooks(query) {

    const text =
        String(query || "")
            .trim()
            .toLowerCase();

    const books =
        getGravityBooks();

    if (!text) {
        return books;
    }

    return books.filter(book => {

        const title =
            String(book.title || "").toLowerCase();

        const author =
            String(book.author || "").toLowerCase();

        const category =
            String(book.category || "").toLowerCase();

        const language =
            String(book.language || "").toLowerCase();

        const description =
            String(book.description || "").toLowerCase();

        return (
            title.includes(text) ||
            author.includes(text) ||
            category.includes(text) ||
            language.includes(text) ||
            description.includes(text)
        );

    });

}


function getGravityBooksByCategory(category) {

    const books =
        getGravityBooks();

    if (
        !category ||
        category === "الكل"
    ) {
        return books;
    }

    return books.filter(
        book =>
            String(book.category || "") === category
    );

}


function openGravityBook(book) {

    const params =
        new URLSearchParams({

            title:
                book.title || "",

            author:
                book.author || "",

            category:
                book.category || "",

            description:
                book.description || "",

            url:
                book.url || "",

            language:
                book.language || ""

        });

    window.location.href =
        "book.html?" + params.toString();

    }
